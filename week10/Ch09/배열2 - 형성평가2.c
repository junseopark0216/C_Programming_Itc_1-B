/*
문제
학생들의 점수를 입력받다가 0이 입력되면 그 때까지 입력받은 점수를 10점 단위로 구분하 여 점수대별 학생 수를 출력하는 프로그램을 작성하시오. (한 명도 없는 점수는 출력하지 않는다.)

예제
입력
63 80 95 100 46 64 88 0

출력
100 : 1
90 : 1
80 : 2
60 : 2
40 : 1
*/
#include <stdio.h>

int main() {
    int score;
    int s[11] = {0};    
    while (1) {
        scanf("%d", &score);
        if (score == 0) {
            break;
        }
        s[score / 10]++;    // 63 → s[6]++, 100 → s[10]++
    }
    for (int i = 10; i >= 0; i--) {    
        if (s[i] != 0) {    
            printf("%d : %d\n", i * 10, s[i]);    
        }
    }

    return 0;
}