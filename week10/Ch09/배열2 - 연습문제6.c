/*
학생 3명의 국어, 영어, 수학 세 과목의 점수를 입력받아 학생별 총점과 과목별 합계를 아래와 같이 출력하는 프로그램을 작성하시오.
입력
95 100 88
85 60 93
66 99 88

출력
95 100 88 283
85 60 93 238
66 99 88 253
246 259 269 774
*/

#include <stdio.h>

int main() {
    int a[4][4] = {0};
    for (int i=0; i<3; i++) {
        for (int j=0; j<3; j++) {
            scanf("%d", &a[i][j]);
        }
        a[i][3] = a[i][0] + a[i][1] + a[i][2];
    }
    for (int j=0; j<4; j++) {
        a[3][j] = a[0][j] + a[1][j] + a[2][j];
    }

    for (int i=0; i<4; i++) {
        for (int j=0; j<4; j++) {
            printf("%d ", a[i][j]);
        }
    printf("\n");
    }
}