/*
문제

10 미만의 자연수 두 개를 입력받아서 첫 번째 항과 두 번째 항을 입력받은 수로 초기화시킨 후 세 번째 항부터는 전전항과 전항의 합을 구하여 그 합의 1의 자리로 채워서 차례로 10개를 출력하는 프로그램을 작성하시오.

예제
입력
3 5

출력
3 5 8 3 1 4 5 9 4 3
*/

#include <stdio.h>

int main() {
    int n1, n2;
    int a[10];
    scanf("%d %d", &n1, &n2);
    a[0] = n1;
    a[1] = n2;
    for (int i=2; i<10; i++) {
        a[i] = (a[i-1] + a[i-2])%10;
    }
    for (int i=0; i<10; i++) {
        printf("%d ", a[i]);
    }
    

}